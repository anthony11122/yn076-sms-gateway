def lookup(imsi=None, iccid=None) -> dict:
    """IMSI 优先(运营商精度), ICCID 兜底(国家精度)。返回 country/iso/flag/carrier/source/raw。"""
    imsi = re.sub(r'\D', '', str(imsi or ''))
    iccid = re.sub(r'\D', '', str(iccid or ''))
    if len(imsi) >= 5:
        mcc, mnc = imsi[:3], imsi[3:5]
        if mcc in ('460', '461', '462', '463', '464', '465', '466', '467'):
            carrier = CN_MNC.get(mnc)
            if not carrier:
                side = '中国广电' if mcc == '460' and mnc in ('15',) else None
                carrier = side or f'中国运营商(MNC {mnc})'
            return {'country': '中国', 'iso': 'CN', 'flag': '🇨🇳', 'carrier': carrier, 'source': 'imsi', 'raw': imsi}
        if mcc in MCC_COUNTRY:
            c, iso, flag = MCC_COUNTRY[mcc]
            return {'country': c, 'iso': iso, 'flag': flag, 'carrier': None, 'source': 'imsi', 'raw': imsi}
    if len(iccid) >= 3:
        for plen in (5, 4, 3, 2):
            entry = ICCID_PREFIX.get(iccid[:plen])
            if entry:
                return {'country': entry[0], 'iso': entry[1], 'flag': entry[2], 'carrier': None, 'source': 'iccid', 'raw': iccid}
    if imsi or iccid:
        return {'country': None, 'iso': None, 'flag': None, 'carrier': None, 'source': 'unknown', 'raw': imsi or iccid}
    return {'country': None, 'iso': None, 'flag': None, 'carrier': None, 'source': None, 'raw': None}


def brief(dongle_status):
    """从 dongle /status 响应提取识别摘要, 供 /api/status 的 sim 字段与面板显示。"""
    if not isinstance(dongle_status, dict):
        return None
    info = lookup(dongle_status.get('imsi'), dongle_status.get('iccid'))
    if not info.get('country'):
        return None
    label = f"{info['flag']} {info['country']}"
    if info.get('carrier'):
        label += f" · {info['carrier']}"
    iccid = re.sub(r'\D', '', str(dongle_status.get('iccid') or ''))
    return {
        'label': label,
        'country': info['country'],
        'iso': info['iso'],
        'carrier': info.get('carrier'),
        'source': info['source'],
        'iccid_tail': iccid[-6:] if len(iccid) >= 6 else None,
    }
